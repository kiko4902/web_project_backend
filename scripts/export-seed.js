// Regenerates supabase/seed.sql from the catalog tables of the connected
// database. User data (profiles, reviews, watchlists) is never exported.
//
//   npm run db:export-seed
require('dotenv').config({ quiet: true });
const fs = require('fs');
const path = require('path');
const { connect } = require('./db');

const ROWS_PER_INSERT = 100;

function literal(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

function inserts(table, columns, rows) {
  const chunks = [];
  for (let i = 0; i < rows.length; i += ROWS_PER_INSERT) {
    const values = rows
      .slice(i, i + ROWS_PER_INSERT)
      .map((row) => `  (${columns.map((column) => literal(row[column])).join(', ')})`)
      .join(',\n');
    chunks.push(`insert into public.${table} (${columns.join(', ')}) values\n${values};`);
  }
  return chunks.join('\n\n');
}

async function main() {
  const client = await connect();
  try {
    const movieColumns = [
      'id',
      'title',
      'overview',
      'poster_url',
      'certificate',
      'runtime',
      'imdb_rating',
      'meta_score',
      'no_of_votes',
      'gross',
      'release_date',
    ];
    // numeric and bigint come back as strings; cast so they are written unquoted.
    const movies = await client.query(`
      select id, title, overview, poster_url, certificate, runtime,
             imdb_rating::float8 as imdb_rating, meta_score::float8 as meta_score,
             no_of_votes::float8 as no_of_votes, gross,
             release_date::float8 as release_date
      from public.movies order by id`);
    const genres = await client.query('select id, name from public.genres order by id');
    const movieGenres = await client.query(
      'select movie_id, genre_id from public.movie_genres order by movie_id, genre_id',
    );

    const sql = [
      '-- Movie catalog seed. Generated by scripts/export-seed.js; do not edit by hand.',
      '-- Source data: the public "IMDb Top 1000 movies" dataset.',
      '',
      inserts('genres', ['id', 'name'], genres.rows),
      '',
      inserts('movies', movieColumns, movies.rows),
      '',
      inserts('movie_genres', ['movie_id', 'genre_id'], movieGenres.rows),
      '',
      "select setval('public.genres_id_seq', (select max(id) from public.genres));",
      "select setval('public.movies_id_seq', (select max(id) from public.movies));",
      '',
    ].join('\n');

    fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'seed.sql'), sql);
    console.log(
      `wrote supabase/seed.sql: ${genres.rowCount} genres, ${movies.rowCount} movies, ${movieGenres.rowCount} movie_genres`,
    );
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
